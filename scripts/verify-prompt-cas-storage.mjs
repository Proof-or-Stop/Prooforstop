import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readdirSync, readFileSync, writeFileSync, renameSync, symlinkSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { StoryStore } from '../packages/main/dist/core/store.js';
import { domainSeparatedDigest } from '../packages/main/dist/core/prompt-contracts.js';
const root = mkdtempSync(join(tmpdir(), 'prompt-body-cas-'));
try {
  const store = new StoryStore(root), storyId = 'B-prompt-cas';
  const body = 'Exact prompt with Unicode 渲染 and repeated context.\n'.repeat(400);
  const digest = domainSeparatedDigest('assembled-prompt.raw-utf8.v1', body);
  store.writeReviewPromptBody(storyId, body, digest);
  const dir = store.storyFilePath(storyId, 'prompt-bodies'), path = join(dir, `${digest}.txt`);
  const mtime = statSync(path).mtimeMs;
  store.writeReviewPromptBody(storyId, body, digest);
  assert.deepEqual(readdirSync(dir), [`${digest}.txt`]);
  assert.equal(statSync(path).mtimeMs, mtime, 'same body is not rewritten');
  const runs = Array.from({length:55}, (_, i) => ({ storyId, reviewRunId:`${storyId}:RR-${i}`, envelopeId:`envelope-${i}`, promptHash:digest, assembledPromptRef:digest }));
  store.writeReviewRuns(storyId, { runs });
  const metadataPath = store.storyFilePath(storyId, 'review-runs.json');
  const slimBytes = statSync(metadataPath).size, inlineBytes = Buffer.byteLength(JSON.stringify({runs:runs.map(run=>({...run,assembledPrompt:body}))}));
  assert.ok(slimBytes < inlineBytes / 10, '55-record workload stores compact references');
  renameSync(path, `${path}.hold`);
  assert.equal(store.readReviewRuns(storyId).runs.length,55,'slim reader must not read the unavailable body');
  assert.throws(()=>store.readReviewPrompt(runs[0]), /ENOENT/);
  renameSync(`${path}.hold`,path);
  assert.equal(store.readReviewPrompt(runs[0]),body);
  assert.throws(()=>store.readReviewPrompt({...runs[0],assembledPromptRef:'../escape'}), /conflicts/);
  assert.throws(()=>store.readReviewPrompt({...runs[0],assembledPrompt:body}), /conflicts/);
  writeFileSync(path,'tampered');
  assert.throws(()=>store.readReviewPrompt(runs[0]), /digest mismatch/);
  assert.throws(()=>store.writeReviewPromptBody(storyId,body,digest), /digest mismatch/);
  assert.equal(readFileSync(path,'utf8'),'tampered','corrupt objects are never silently replaced');
  rmSync(path); symlinkSync(metadataPath,path);
  assert.throws(()=>store.readReviewPrompt(runs[0]));
  rmSync(path);
  const replacement = '\ufffd', replacementDigest = domainSeparatedDigest('assembled-prompt.raw-utf8.v1',replacement);
  writeFileSync(join(dir,`${replacementDigest}.txt`),Buffer.from([255]));
  assert.throws(()=>store.readReviewPrompt({...runs[0],promptHash:replacementDigest,assembledPromptRef:replacementDigest}), /exact UTF-8/);
  const legacy={...runs[0],assembledPrompt:body};delete legacy.assembledPromptRef;
  store.writeReviewRuns(storyId,{runs:[legacy]});
  const before=readFileSync(metadataPath,'utf8');assert.equal(store.readReviewPrompt(store.readReviewRuns(storyId).runs[0]),body);
  assert.equal(readFileSync(metadataPath,'utf8'),before,'legacy history is not migrated during reads');
  console.log(`PASS U12 prompt CAS dedup, slim reads, corruption refusal, legacy bytes; 55-run fixture metadata ${inlineBytes} -> ${slimBytes} bytes`);
} finally { rmSync(root,{recursive:true,force:true}); }
