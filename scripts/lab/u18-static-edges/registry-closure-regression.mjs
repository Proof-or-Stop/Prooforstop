import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {spawnSync} from 'node:child_process';
const root=fs.realpathSync(process.argv[2]||process.cwd());
const manifest=process.argv[3]||path.join(root,'scripts/lab/u18-static-edges/exceptions.json');
const outputRoot=fs.mkdtempSync(path.join(os.tmpdir(),'proof-or-stop-static-registry-'));
const out=path.join(outputRoot,'report.json');
const startedAt=new Date().toISOString(),start=performance.now();
const result=spawnSync(process.execPath,[path.join(root,'scripts/verify-validation-static-edges.mjs'),root,manifest],{cwd:root,env:{...process.env,U18_STATIC_REPORT_PATH:out},encoding:'utf8',timeout:60000});
process.stdout.write(result.stdout||'');process.stderr.write(result.stderr||'');
assert.ifError(result.error);assert.equal(result.signal,null,'scanner setup/timeout is not registry RED');
assert(fs.existsSync(out),'scanner must reach actual report');const report=JSON.parse(fs.readFileSync(out,'utf8'));assert.equal(report.schema,'u18-static-edges.v1');
console.log(JSON.stringify({startedAt,endedAt:new Date().toISOString(),seconds:(performance.now()-start)/1000,reportPath:out,status:result.status,summary:report.summary,stale:report.staleExceptions.length,configDrift:report.configDrift,manifest}));
assert.equal(result.status,0,'STATIC_REGISTRY_EXACT_CLOSURE_REQUIRED');
assert.equal(report.configDrift,false);assert.deepEqual(report.staleExceptions,[]);
for(const field of ['needsReview','nested','unexpandedCommands'])assert.equal(report.summary[field],0,field);
assert.match(result.stdout,/U18_STATIC_PASS/);
console.log('STATIC_REGISTRY_EXACT_CLOSURE PASS');
