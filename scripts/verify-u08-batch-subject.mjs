import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { withSignedReviewerBatchFixture } from './lab/u08-batch-admission/subject-fixture.mjs';
const repo = path.resolve(process.argv[2] || path.join(path.dirname(fileURLToPath(import.meta.url)), '..'));
const modulePath = path.join(repo, 'packages/main/dist/core/reviewer-batch-subject.js');
assert.ok(fs.existsSync(modulePath), 'U08_BATCH_VERIFIED_SUBJECT_IMPLEMENTATION_REQUIRED');
const { deriveReviewerBatchSubject, validateReviewerBatchAssignments, assertReviewerBatchAssignmentMatch } = await import(pathToFileURL(modulePath));
await withSignedReviewerBatchFixture(repo, async ({ root, storyId, store, begin, git }) => {
  const derive = () => deriveReviewerBatchSubject(store, root, { storyId });
  assert.throws(derive, /SIGNED_CURRENT_OPEN_EPOCH/);
  begin();
  const first = derive();
  assert.equal(derive().subjectIdentity, first.subjectIdentity);
  const assignments = first.requiredLanes.map((lane, index) => index ? { lane, kind: 'native' } : { lane, kind: 'managed', host: 'codex' });
  validateReviewerBatchAssignments(first.requiredLanes, assignments);
  assert.throws(() => validateReviewerBatchAssignments(first.requiredLanes, assignments.slice(1)), /MISSING/);
  assert.throws(() => validateReviewerBatchAssignments(first.requiredLanes, [...assignments, assignments[0]]), /DUPLICATE/);
  assert.throws(() => validateReviewerBatchAssignments(first.requiredLanes, [{ lane: 'unknown', kind: 'native' }]), /UNKNOWN/);
  assert.throws(() => validateReviewerBatchAssignments(first.requiredLanes, [{ ...assignments[0], kind: 'native' }, ...assignments.slice(1)]), /NATIVE_ASSIGNMENT_HAS_MANAGED_HOST/);
  assert.throws(() => validateReviewerBatchAssignments(first.requiredLanes, [{ lane: assignments[0].lane, kind: 'managed' }, ...assignments.slice(1)]), /REQUIRES_EXPLICIT_HOST/);
  assert.throws(() => assertReviewerBatchAssignmentMatch(assignments, { ...assignments[0], host: 'claude' }), /MISMATCH/);
  assert.throws(() => assertReviewerBatchAssignmentMatch(assignments, { lane: assignments[0].lane, kind: 'native' }), /MISMATCH/);
  assert.throws(() => deriveReviewerBatchSubject(store, root, { storyId, wave: 999 }), /REQUEST_MISMATCH/);
  assert.throws(() => deriveReviewerBatchSubject(store, root, { storyId, epochId: 'other' }), /REQUEST_MISMATCH/);
  const original = store.readStory(storyId);
  store.writeStory(storyId, { ...original, phase: 'DEV' });
  assert.throws(derive, /REQUIRES_CURRENT_REVIEW/);
  store.writeStory(storyId, { ...original, currentReviewRound: 'other-round' });
  assert.throws(derive, /SIGNED_CURRENT_OPEN_EPOCH/);
  store.writeStory(storyId, original);
  const signedEpochs = store.readReviewInventoryEpochs(storyId), corrupt = structuredClone(signedEpochs);
  corrupt.epochs.at(-1)._hash = 'tampered-signature';
  store.writeReviewInventoryEpochs(storyId, corrupt);
  assert.throws(derive, /signature mismatch/);
  store.writeReviewInventoryEpochs(storyId, signedEpochs);
  assert.equal(derive().subjectIdentity, first.subjectIdentity);
  fs.writeFileSync(path.join(root, 'packages/main/src/subject.ts'), 'export const value=2;');
  git('add', 'packages/main/src/subject.ts'); git('commit', '-qm', 'material drift');
  const before = JSON.stringify(store.readReviewInventoryEpochs(storyId));
  assert.throws(derive, /CUTOFF_DRIFT/);
  assert.equal(JSON.stringify(store.readReviewInventoryEpochs(storyId)), before, 'readonly stale check must not invalidate or rewrite signed epoch');
});
console.log('U08_BATCH_SIGNED_SUBJECT_PASS actual begin signature/stable identity/exact roster/host mismatch/wrong epoch+wave+phase+round/tamper/material drift readonly');
