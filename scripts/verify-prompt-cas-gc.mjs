import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { StoryStore } from '../packages/main/dist/core/store.js';
import { domainSeparatedDigest } from '../packages/main/dist/core/prompt-contracts.js';
import { createReviewInventoryHandlers } from '../packages/main/dist/handlers/review-inventory.js';
const root = mkdtempSync(join(tmpdir(), 'prompt-gc-'));
try {
  const store = new StoryStore(root), storyId = 'B-prompt-gc';
  store.writeStory(storyId, { storyId, name: 'prompt gc', phase: 'DEV', events: [], createdAt: new Date().toISOString() });
  const handlers = createReviewInventoryHandlers({ root, scanRoot: root, store });
  assert.equal(typeof handlers.review_prompt_gc, 'function', 'U12 prompt GC must reclaim orphans while preserving every gate reference');
  const put = body => { const digest = domainSeparatedDigest('assembled-prompt.raw-utf8.v1', body); store.writeReviewPromptBody(storyId, body, digest); return digest; };
  const live = put('current signed reviewer body'), historical = put('historical envelope body'), orphan = put('interrupted publication body');
  const path = digest => store.storyFilePath(storyId, `prompt-bodies/${digest}.txt`);
  store.writeReviewRuns(storyId, { runs: [{ storyId, reviewRunId: 'run-live', envelopeId: 'env-live', promptHash: live, assembledPromptRef: live }] });
  store.writePromptEnvelopes(storyId, { envelopes: [{ envelopeId: 'env-live', assembledPromptDigest: live }, { envelopeId: 'env-old', assembledPromptDigest: historical }] });
  store.writeReviewPasses(storyId, { passes: [{ id: 'pass-live', reviewRunId: 'run-live', envelopeId: 'env-live' }] });
  store.writeFindings(storyId, { findings: [] });
  const metadata = ['review-runs.json', 'prompt-envelopes.json', 'review-passes.json', 'findings.json'];
  const before = metadata.map(file => readFileSync(store.storyFilePath(storyId, file), 'utf8'));
  assert.match(handlers.review_prompt_gc({ storyId }), /removed=1/);
  assert.ok(existsSync(path(live))); assert.ok(existsSync(path(historical))); assert.equal(existsSync(path(orphan)), false);
  assert.deepEqual(metadata.map(file => readFileSync(store.storyFilePath(storyId, file), 'utf8')), before, 'GC never rewrites gate metadata or history');
  assert.match(handlers.review_prompt_gc({ storyId }), /removed=0/, 'GC retry is idempotent');
  put('interrupted publication body');
  const passesPath = store.storyFilePath(storyId, 'review-passes.json');
  writeFileSync(passesPath, '{broken');
  assert.throws(() => handlers.review_prompt_gc({ storyId }), /prompt GC/);
  assert.ok(existsSync(path(orphan)), 'malformed metadata cannot be interpreted as no references');
  writeFileSync(passesPath, before[2]);
  store.writeReviewPasses(storyId, { passes: [{ id: 'dangling-pass', reviewRunId: 'missing-run' }] });
  assert.throws(() => handlers.review_prompt_gc({ storyId }), /dangling/);
  assert.ok(existsSync(path(orphan)), 'dangling gate references stop all deletion');
  writeFileSync(passesPath, before[2]);
  rmSync(path(live));
  assert.throws(() => handlers.review_prompt_gc({ storyId }), /prompt GC/);
  assert.ok(existsSync(path(orphan)), 'missing referenced body stops all deletion');
  put('current signed reviewer body');
  assert.match(handlers.review_prompt_gc({ storyId }), /removed=1/);
  assert.equal(store.readReviewPrompt(store.readReviewRuns(storyId).runs[0]), 'current signed reviewer body');
  console.log('PASS U12 GC preserves gate and historical references, refuses corrupt or dangling inputs, and reclaims only orphans');
} finally { rmSync(root, { recursive: true, force: true }); }
