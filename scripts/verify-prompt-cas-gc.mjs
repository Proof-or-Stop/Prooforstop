import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readFileSync, writeFileSync, existsSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { StoryStore } from '../packages/main/dist/core/store.js';
import { domainSeparatedDigest } from '../packages/main/dist/core/prompt-contracts.js';
import { createReviewInventoryHandlers } from '../packages/main/dist/handlers/review-inventory.js';
const root = mkdtempSync(join(tmpdir(), 'prompt-gc-'));
try {
  const store = new StoryStore(root), storyId = 'B-prompt-gc';
  store.writeStory(storyId, { storyId, name: 'prompt gc', phase: 'DEV', events: [], createdAt: new Date().toISOString() });
  const handlers = createReviewInventoryHandlers({ root, scanRoot: root, store });
  assert.equal(typeof handlers.review_prompt_gc, 'function', 'U12 prompt GC must reclaim orphans while preserving every gate reference');
  const put = body => { const digest = domainSeparatedDigest('assembled-prompt.raw-utf8.v1', body); store.writeReviewPromptBody(storyId, body, digest); return digest; };
  const orphan = put('interrupted publication body');
  const path = digest => store.storyFilePath(storyId, `prompt-bodies/${digest}.txt`);
  store.writeReviewRuns(storyId, { runs: [] });
  store.writePromptEnvelopes(storyId, { envelopes: [] });
  store.writeReviewPasses(storyId, { passes: [] });
  store.writeFindings(storyId, { findings: [] });
  const metadata = ['review-runs.json', 'prompt-envelopes.json', 'review-passes.json', 'findings.json'];
  const before = metadata.map(file => readFileSync(store.storyFilePath(storyId, file), 'utf8'));
  assert.match(handlers.review_prompt_gc({ storyId }), /removed=1/);
  assert.equal(existsSync(path(orphan)), false);
  assert.deepEqual(metadata.map(file => readFileSync(store.storyFilePath(storyId, file), 'utf8')), before, 'GC never rewrites metadata');
  assert.match(handlers.review_prompt_gc({ storyId }), /removed=0/);
  put('interrupted publication body');
  const passesPath = store.storyFilePath(storyId, 'review-passes.json');
  writeFileSync(passesPath, '{broken');
  assert.throws(() => handlers.review_prompt_gc({ storyId }), /prompt GC/);
  assert.ok(existsSync(path(orphan)), 'malformed metadata cannot be interpreted as no references');
  store.writeReviewPasses(storyId, { passes: [{ id: 'unsigned-pass', reviewRunId: 'missing-run' }] });
  assert.throws(() => handlers.review_prompt_gc({ storyId }), /signature/);
  assert.ok(existsSync(path(orphan)), 'unsigned metadata stops all deletion');
  writeFileSync(passesPath, before[2]);
  writeFileSync(store.findingLedgerPath(storyId), '{broken');
  assert.throws(() => handlers.review_prompt_gc({ storyId }), /prompt GC/);
  assert.ok(existsSync(path(orphan)), 'damaged authoritative ledger stops all deletion');
  rmSync(store.findingLedgerPath(storyId));
  symlinkSync(join(root, 'missing-ledger'), store.findingLedgerPath(storyId));
  assert.throws(() => handlers.review_prompt_gc({ storyId }), /regular file/);
  assert.ok(existsSync(path(orphan)), 'broken ledger symlink is not absent authority');
  rmSync(store.findingLedgerPath(storyId));
  assert.match(handlers.review_prompt_gc({ storyId }), /removed=1/);
  console.log('PASS U12 GC refuses unsigned metadata and corrupt authoritative ledger, and reclaims orphans idempotently');
} finally { rmSync(root, { recursive: true, force: true }); }
