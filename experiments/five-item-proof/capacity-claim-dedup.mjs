import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {declaredValidationCapacity} from '../../packages/main/dist/core/validation-execution-lock.js';
import {canonicalizeEntries,claimsConflict} from '../../packages/main/dist/core/keyed-scheduler.js';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const commands=JSON.parse(readFileSync(root+'/proof-or-stop.config.json')).validate.commands;
const selected=declaredValidationCapacity(commands,root);
assert.equal(selected.resources.length,new Set(selected.resources.map(c=>JSON.stringify(c))).size,'DUPLICATE_REAL_CAPACITY_CLAIMS');
assert.equal(selected.maxConcurrent,2);
assert.deepEqual(declaredValidationCapacity([{label:'undeclared'}],root),{});
const shared={class:'fixed-path',key:'probe',access:'shared'},exclusive={...shared,access:'exclusive'};
const input=[{label:'one',resources:[shared,shared,exclusive]},{label:'two',resources:[shared,exclusive]}];
const aggregate=declaredValidationCapacity(input,root);
const probeClaims=aggregate.resources.filter(r=>r.key===resolve(root,'probe'));assert.equal(probeClaims.length,2,'Shared and exclusive claims are distinct');
const pair=canonicalizeEntries([{name:'owner',resources:aggregate.resources},{name:'reader',resources:[shared]}],root);assert.ok(claimsConflict(...pair),'Dedup cannot remove the exclusive conflict');
const cwdClaims=declaredValidationCapacity([{label:'a',cwd:'a',resources:[shared]},{label:'b',cwd:'b',resources:[shared]}],root).resources;assert.ok(cwdClaims.some(r=>r.key===resolve(root,'a/probe'))&&cwdClaims.some(r=>r.key===resolve(root,'b/probe')),'Different command working directories stay distinct');
assert.throws(()=>declaredValidationCapacity([{label:'invalid',resources:[shared,{...shared,class:'unknown'}]}],root),/unknown resource class/,'Dedup must not mask an invalid declaration');
console.log('CAPACITY_CLAIMS_DEDUP_GREEN '+JSON.stringify({claims:selected.resources.length,commands:commands.length}));
