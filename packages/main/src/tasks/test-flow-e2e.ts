// ── 配置加载 ──

/**
 * 加载用户覆盖配置（从 koala.config.json 的 flows.defaults），支持按 flow 名称分组。
 */
let _userOverrides: Record<string, unknown> | null = null;

function loadUserOverrides(flowName?: string): Record<string, unknown> {
  if (!_userOverrides) {
    const config = loadConfig();
    _userOverrides = {};
    Object.assign(_userOverrides, config.flows.defaults || {});
  }
  // 按 flow 名称取分组覆盖，没有则取顶层
  const flowSpecific = flowName && typeof (_userOverrides as any)[flowName] === 'object'
    ? (_userOverrides as any)[flowName] as Record<string, unknown>
    : {};
  const topLevel = { ..._userOverrides };
  // 删掉非值字段
  for (const k of Object.keys(topLevel)) {
    if (typeof topLevel[k] === 'object' && topLevel[k] !== null && !Array.isArray(topLevel[k])
        && k !== '_patterns' && k !== 'checklist') {
      delete topLevel[k];
    }
  }
  return { ...topLevel, ...flowSpecific };
}

/**
 * 自动生成默认值：根据字段名推导类型，生成合理的 mock 值。
 * 用户配置覆盖自动值。
 */
function autoDefaults(
  inputFields: string[],
  context: Record<string, unknown>,
  flowName?: string,
): Record<string, unknown> {
  const auto: Record<string, unknown> = {};

  // 按字段名猜测类型并生成默认值
  for (const field of inputFields) {
    if (field in context) continue; // context 已有的不需要默认值

    // 常见命名模式 → 默认值
    // 精确匹配优先，模糊匹配在后
    if (/^checklist$/i.test(field)) auto[field] = [{ title: 'E2E item 1' }, { title: 'E2E item 2' }];
    else if (/id$/i.test(field)) auto[field] = 'test-001';
    else if (/name$/i.test(field)) auto[field] = 'e2e-auto';
    else if (/title$/i.test(field)) auto[field] = 'E2E Auto Test';
    else if (/desc/i.test(field)) auto[field] = 'Auto-generated by flow e2e';
    else if (/type$/i.test(field)) auto[field] = 'feature';
    else if (/priority/i.test(field)) auto[field] = 'medium';
    else if (/status/i.test(field)) auto[field] = 'done';
    else if (/url$/i.test(field)) auto[field] = 'http://localhost:3000';
    else if (/email/i.test(field)) auto[field] = 'test@example.com';
    else if (/password|passwd|pwd/i.test(field)) auto[field] = 'test123';
    else if (/user|username|login/i.test(field)) auto[field] = 'testuser';
    else if (/token/i.test(field)) auto[field] = 'test-token-xxx';
    else if (/count|num|size|len/i.test(field)) auto[field] = 1;
    else if (/flag|enabled|active|valid|full/i.test(field)) auto[field] = true;
    else if (/list|items|array/i.test(field)) auto[field] = [];
    else auto[field] = 'test';
  }

  // 动态推导 phase
  if (inputFields.includes('phase') && !context.phase) {
    auto.phase = 'DEV';
  } else if (inputFields.includes('phase')) {
    const currentPhase = context.phase as string;
    const phaseOrder = ['IDEA', 'PLAN', 'DEV', 'TEST', 'DONE'];
    const nextIdx = phaseOrder.indexOf(currentPhase) + 1;
    auto.phase = phaseOrder[Math.min(nextIdx, phaseOrder.length - 1)];
  }

  // 用户配置覆盖
  const overrides = loadUserOverrides(flowName);
  return { ...auto, ...overrides };
}

// ── Types ──

export interface FlowE2EStepResult {
  step: string;
  passed: boolean;
  error?: string;
  input?: unknown;
  output?: unknown;
  hint?: string;
}

export interface FlowE2EResult {
  flow: string;
  steps: FlowE2EStepResult[];
  allPassed: boolean;
}

export interface Sandbox {
  dir: string;
  store: StoryStore;
  handlers: ReturnType<typeof createToolHandlers>;
  cleanup: () => void;
}

export async function createSandbox(realProjectRoot?: string): Promise<Sandbox> {
  const dir = mkdtempSync(join(tmpdir(), 'koala-e2e-'));
  mkdirSync(join(dir, 'docs', 'story', 'actives'), { recursive: true });
  mkdirSync(join(dir, 'docs', 'requirements'), { recursive: true });

  const store = new StoryStore(dir);
  const handlers = createToolHandlers(store, realProjectRoot || dir);

  const cleanup = () => {
    rmSync(dir, { recursive: true, force: true });
  };

  return { dir, store, handlers, cleanup };
}

// ── Field Parsing ──

/**
 * 解析 @input/@output 注释字符串，提取字段名列表。
 * "{ name, title, description }" → ["name", "title", "description"]
 * "{ storyId, phase, checklist? }" → ["storyId", "phase", "checklist"]
 * "(none)" → []
 * "storyId (IDEA or PLAN)" → ["storyId"]
 */
function parseFieldNames(annotation: string | undefined): string[] {
  if (!annotation || annotation === '(none)') return [];

  // 尝试匹配 { field1, field2, field3? } 格式
  const braceMatch = annotation.match(/\{([^}]+)\}/);
  if (braceMatch) {
    return braceMatch[1]
      .split(',')
      .map(s => s.trim().replace(/\?$/, ''))
      .filter(s => s.length > 0 && /^[a-zA-Z_]\w*$/.test(s));
  }

  // 尝试匹配开头的标识符：如 "storyId (IDEA or PLAN)"
  const idMatch = annotation.match(/^([a-zA-Z_]\w*)/);
  if (idMatch) return [idMatch[1]];

  return [];
}

/**
 * 从函数返回值中提取键值对，合并到 context。
 * 支持 JSON 字符串、普通对象、含 ID 的文本。
 */
function extractOutputToContext(
  result: unknown,
  outputFields: string[],
  context: Record<string, unknown>,
): void {
  if (result === undefined || result === null) return;

  let obj: Record<string, unknown> = {};

  if (typeof result === 'string') {
    // 尝试 JSON 解析
    try {
      const parsed = JSON.parse(result);
      if (typeof parsed === 'object' && parsed !== null) {
        obj = parsed;
      }
    } catch {
      // 非 JSON，从文本中提取常见 ID 模式
      // 从文本中提取字段的模式（内置 + 可通过 flow-defaults.json 的 _patterns 扩展）
      const builtinPatterns: Array<{ field: string; regex: RegExp }> = [
        { field: 'storyId', regex: /Story\s+(B-[a-f0-9]+)/i },
        { field: 'bugId', regex: /Bug\s+(BUG-\d+)/ },
        { field: 'itemId', regex: /(CHK-\d+)/ },
        { field: 'phase', regex: /advanced to\s+(\w+)/ },
        { field: 'phase', regex: /\((\w+)\)\s*(?:with|$)/ },
      ];
      const extraPatterns = loadConfig().flows.patterns as Array<{ field: string; regex: string }> | undefined;
      const patterns = [
        ...builtinPatterns,
        ...(extraPatterns || []).map(p => ({ field: p.field, regex: new RegExp(p.regex) })),
      ];
      for (const { field, regex } of patterns) {
        const m = result.match(regex);
        if (m) obj[field] = m[1];
      }
    }
  } else if (typeof result === 'object') {
    obj = result as Record<string, unknown>;
  }

  // 只提取 outputFields 中声明的字段（如果有声明）
  // 如果 outputFields 为空，提取所有
  if (outputFields.length > 0) {
    for (const field of outputFields) {
      if (field in obj) {
        context[field] = obj[field];
      }
    }
  } else {
    Object.assign(context, obj);
  }
}

/**
 * 根据 @input 字段名从 context 构建输入参数。
 * 如果 context 中没有某个字段，用默认 mock 值。
 */
function buildInputFromContext(
  inputFields: string[],
  context: Record<string, unknown>,
  flowName?: string,
): unknown {
  if (inputFields.length === 0) return undefined;

  const defaults = autoDefaults(inputFields, context, flowName);

  const input: Record<string, unknown> = {};
  for (const field of inputFields) {
    // phase 特殊处理：永远用推导的下一步，不用 context 中的当前值
    if (field === 'phase') {
      input[field] = defaults[field];
    } else if (field in context) {
      input[field] = context[field];
    } else if (field in defaults) {
      input[field] = defaults[field];
    }
  }

  return input;
}

// ── Sandbox Preparation ──

/**
 * 确保 sandbox 环境满足函数执行的前置条件。
 * 基于 context 中的数据自动判断，不按函数名硬编码。
 */
function ensureSandboxReady(
  sandboxDir: string,
  handlers: any,
  context: Record<string, unknown>,
): void {
  const storyId = context.storyId as string | undefined;
  if (!storyId) return;

  // 从 checklist 中提取第一个 itemId 到 context（如果还没有）
  if (!context.itemId) {
    try {
      const cl = handlers.checklist_get({ storyId });
      if (cl.items.length > 0) {
        context.itemId = cl.items[0].id;
      }
    } catch { /* ignore */ }
  }

  // 确保有 stub 代码文件（让 task_coverage 通过）
  const fakeSrcDir = join(sandboxDir, 'packages', 'main', 'src');
  if (!existsSync(join(fakeSrcDir, 'e2e-stub.ts'))) {
    mkdirSync(fakeSrcDir, { recursive: true });
    writeFileSync(
      join(fakeSrcDir, 'e2e-stub.ts'),
      [
        'export function e2eStub() {}',
        '',
      ].join('\n'),
      'utf-8',
    );
  }

  // 确保 checklist 全 done
  try {
    const cl = handlers.checklist_get({ storyId });
    for (const item of cl.items) {
      if (item.status !== 'done') {
        handlers.checklist_update({ storyId, itemId: item.id, status: 'done' });
      }
    }
  } catch {
    // ignore
  }
}

// ── Failure Diagnosis ──

/**
 * 根据错误信息生成修复提示。
 */
function diagnoseFailure(
  errorMsg: string,
  functionName: string,
  inputFields: string[],
  input: unknown,
  context: Record<string, unknown>,
): string {
  const inputObj = input as Record<string, unknown> | undefined;

  // 字段缺失/undefined
  if (/undefined|not found|missing/i.test(errorMsg)) {
    const undefinedFields = inputFields.filter(f =>
      inputObj && (inputObj[f] === undefined || inputObj[f] === null)
    );
    if (undefinedFields.length > 0) {
      return `输入字段 [${undefinedFields.join(', ')}] 为空。` +
        `请在 flow-defaults.json 中为这些字段配置默认值，` +
        `或检查上一步的 @output 是否包含这些字段。`;
    }
  }

  // 状态转换失败
  if (/cannot transition|invalid.*phase/i.test(errorMsg)) {
    return `状态转换失败。当前 context.phase=${context.phase || '未知'}。` +
      `检查 @flow 步骤顺序是否正确，或前置步骤是否成功完成。`;
  }

  // 文件不存在
  if (/file not found|ENOENT/i.test(errorMsg)) {
    return `依赖文件不存在。如果是 sandbox 环境问题，检查 ensureSandboxReady 是否覆盖了该场景。` +
      `如果是代码路径问题，检查 @input 中的路径字段是否正确。`;
  }

  // 通用提示
  return `函数 ${functionName} 执行出错。` +
    `传入的参数: ${JSON.stringify(input)}。` +
    `当前 context: ${JSON.stringify(Object.keys(context))}。` +
    `请检查函数逻辑或 @input/@output 注释是否匹配。`;
}

// ── Flow E2E Runner ──

export async function runFlowE2E(flowName: string, scanRoot: string): Promise<FlowE2EResult> {
  const tasks = scan(scanRoot);
  const flows = extractFlows(tasks);
  const targetFlow = flows.find(f => f.name === flowName);

  if (!targetFlow) {
    return {
      flow: flowName,
      steps: [{ step: 'flow-lookup', passed: false, error: `Flow "${flowName}" not found` }],
      allPassed: false,
    };
  }

  // projectRoot = MCP server cwd（即项目根目录），不从 scanRoot 反推
  const projectRoot = process.env.KOALA_PROJECT_ROOT || process.cwd();
  const sandbox = await createSandbox(projectRoot);
  const steps: FlowE2EStepResult[] = [];
  const context: Record<string, unknown> = {};

  try {
    const { handlers, dir } = sandbox;

    for (const flowStep of targetFlow.steps) {
      const fn = (handlers as any)[flowStep.functionName];

      if (typeof fn !== 'function') {
        steps.push({
          step: `${flowStep.functionName} (step ${flowStep.step})`,
          passed: false,
          error: `Function "${flowStep.functionName}" not found in handlers`,
        });
        continue;
      }

      const stepName = `${flowStep.functionName} (step ${flowStep.step})`;
      const inputFields = parseFieldNames(flowStep.input);
      let input: unknown;

      try {
        ensureSandboxReady(dir, handlers, context);
        input = buildInputFromContext(inputFields, context, flowName);
        const result = fn.call(handlers, input);

        const outputFields = parseFieldNames(flowStep.output);
        extractOutputToContext(result, outputFields, context);

        steps.push({ step: stepName, passed: true, input, output: result });
      } catch (err: any) {
        // 生成修复提示
        const hint = diagnoseFailure(err.message, flowStep.functionName, inputFields, input, context);
        steps.push({ step: stepName, passed: false, error: err.message, input, hint });
      }
    }
  } finally {
    sandbox.cleanup();
  }

  return {
    flow: flowName,
    steps,
    allPassed: steps.every(s => s.passed),
  };
}
