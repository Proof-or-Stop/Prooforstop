// ── Configuration loading ──

/**
 * Load user override config (from lattice.config.json's flows.defaults), supports grouping by flow name.
 */
let _userOverrides: Record<string, unknown> | null = null;

function defaultBackground(): string {
  return [
    '## Trigger Event',
    '2026-04-26 B-e2e automated regression requires creating a minimal story to confirm that the current CLI lifecycle remains executable from creation, advancement, through checklist updates.',
    'This background is deliberately written as complete context rather than a short placeholder, to avoid e2e bypassing the real four-part gate of story_create.',
    '',
    '## Key Insights',
    'The current Lattice story_create already requires background to be a source-of-truth input; old e2e passing only title and description would falsely report process failures.',
    'So the auto-default values must simulate context provided by a real user, rather than relying on the handler relaxing validation.',
    '',
    '## Solution Tradeoffs',
    'e2e adopts a minimal but valid story input, preserving the current gates and signing mechanism, without adding special exemptions in the test path.',
    'This validates the public CLI flow and also surfaces issues early when background schema drifts in the future.',
    '',
    '## Conversational Texture',
    'What the user cares about is whether the latest Lattice can be reliably used by projects, so this regression should provide clear motivation, constraints, and acceptance context like a real session.',
    'Test content stays concise, but does not sacrifice basic respect for the product flow.',
  ].join('\n');
}

function loadUserOverrides(flowName?: string): Record<string, unknown> {
  if (!_userOverrides) {
    const config = loadConfig();
    _userOverrides = {};
    Object.assign(_userOverrides, config.flows.defaults || {});
  }
  // Take group override by flow name; fall back to top-level if absent
  const flowSpecific = flowName && typeof (_userOverrides as any)[flowName] === 'object'
    ? (_userOverrides as any)[flowName] as Record<string, unknown>
    : {};
  const topLevel = { ..._userOverrides };
  // Drop non-value fields
  for (const k of Object.keys(topLevel)) {
    if (typeof topLevel[k] === 'object' && topLevel[k] !== null && !Array.isArray(topLevel[k])
        && k !== '_patterns' && k !== 'checklist') {
      delete topLevel[k];
    }
  }
  return { ...topLevel, ...flowSpecific };
}

/**
 * Auto-generate defaults: infer type from field name and produce reasonable mock values.
 * User config overrides auto values.
 */
function autoDefaults(
  inputFields: string[],
  context: Record<string, unknown>,
  flowName?: string,
): Record<string, unknown> {
  const auto: Record<string, unknown> = {};

  // Guess type by field name and produce default values
  for (const field of inputFields) {
    if (field in context) continue; // No default needed for fields already in context

    // Common naming patterns → default values
    // Exact match takes priority, fuzzy match comes after
    if (/^checklist$/i.test(field)) auto[field] = [
      {
        title: 'Verify current story lifecycle e2e path',
        context: 'E2E regression needs a concrete checklist item with context so current Lattice truth-source gates exercise the real path.',
      },
    ];
    else if (/^background$/i.test(field)) auto[field] = defaultBackground();
    else if (/id$/i.test(field)) auto[field] = 'test-001';
    else if (/name$/i.test(field)) auto[field] = 'e2e-auto';
    else if (/title$/i.test(field)) auto[field] = 'E2E Auto Test';
    else if (/desc/i.test(field)) auto[field] = 'Auto-generated by flow e2e';
    else if (/type$/i.test(field)) auto[field] = 'feature';
    else if (/priority/i.test(field)) auto[field] = 'medium';
    else if (/status/i.test(field)) auto[field] = 'done';
    else if (/url$/i.test(field)) auto[field] = 'http://localhost:3000';
    else if (/email/i.test(field)) auto[field] = 'test@example.com';
    else if (/password|passwd|pwd/i.test(field)) auto[field] = 'test123';
    else if (/user|username|login/i.test(field)) auto[field] = 'testuser';
    else if (/token/i.test(field)) auto[field] = 'test-token-xxx';
    else if (/count|num|size|len/i.test(field)) auto[field] = 1;
    else if (/flag|enabled|active|valid|full/i.test(field)) auto[field] = true;
    else if (/list|items|array/i.test(field)) auto[field] = [];
    else auto[field] = 'test';
  }

  // Dynamically derive phase
  if (inputFields.includes('phase') && !context.phase) {
    auto.phase = 'DEV';
  } else if (inputFields.includes('phase')) {
    const currentPhase = context.phase as string;
    const phaseOrder = ['IDEA', 'INIT', 'INIT_CHECK', 'PLAN', 'DEV', 'REVIEW', 'TEST', 'DONE'];
    const nextIdx = phaseOrder.indexOf(currentPhase) + 1;
    auto.phase = phaseOrder[Math.min(nextIdx, phaseOrder.length - 1)];
  }

  // User config override
  const overrides = loadUserOverrides(flowName);
  return { ...auto, ...overrides };
}

// ── Types ──

export interface FlowE2EStepResult {
  step: string;
  passed: boolean;
  error?: string;
  input?: unknown;
  output?: unknown;
  hint?: string;
}

export interface FlowE2EResult {
  flow: string;
  steps: FlowE2EStepResult[];
  allPassed: boolean;
}

export interface Sandbox {
  dir: string;
  store: StoryStore;
  handlers: ReturnType<typeof createToolHandlers>;
  cleanup: () => void;
}

export async function createSandbox(realProjectRoot?: string): Promise<Sandbox> {
  const dir = mkdtempSync(join(tmpdir(), 'lattice-e2e-'));
  mkdirSync(join(dir, 'docs', 'story', 'actives'), { recursive: true });
  mkdirSync(join(dir, 'docs', 'requirements'), { recursive: true });
  mkdirSync(join(dir, 'packages', 'main', 'src'), { recursive: true });
  writeFileSync(
    join(dir, 'lattice.config.json'),
    JSON.stringify({
      scanRoot: 'packages/main',
      rootDir: 'src',
      outDir: 'packages/main/dist',
      testsDir: 'packages/main/tests',
      fixturesDir: 'packages/main/tests/fixtures',
      storyDir: 'docs/story/actives',
      requirementsDir: 'docs/requirements',
      storyPrefix: 'B',
    }, null, 2),
    'utf-8',
  );

  const store = new StoryStore(dir);
  const handlers = createToolHandlers(store, dir);

  const cleanup = () => {
    rmSync(dir, { recursive: true, force: true });
  };

  return { dir, store, handlers, cleanup };
}

// ── Field Parsing ──

/**
 * Parse @input/@output comment strings, extract list of field names.
 * "{ name, title, description }" → ["name", "title", "description"]
 * "{ storyId, phase, checklist? }" → ["storyId", "phase", "checklist"]
 * "(none)" → []
 * "storyId (IDEA or PLAN)" → ["storyId"]
 */
function parseFieldNames(annotation: string | undefined): string[] {
  if (!annotation || annotation === '(none)') return [];

  // Try to match { field1, field2, field3? } format
  const braceMatch = annotation.match(/\{([^}]+)\}/);
  if (braceMatch) {
    return braceMatch[1]
      .split(',')
      .map(s => s.trim().replace(/\?$/, ''))
      .filter(s => s.length > 0 && /^[a-zA-Z_]\w*$/.test(s));
  }

  // Try to match leading identifier: e.g. "storyId (IDEA or PLAN)"
  const idMatch = annotation.match(/^([a-zA-Z_]\w*)/);
  if (idMatch) return [idMatch[1]];

  return [];
}

/**
 * Extract key-value pairs from function return value, merge into context.
 * Supports JSON strings, plain objects, and text containing IDs.
 */
function extractOutputToContext(
  result: unknown,
  outputFields: string[],
  context: Record<string, unknown>,
): void {
  if (result === undefined || result === null) return;

  let obj: Record<string, unknown> = {};

  if (typeof result === 'string') {
    // Try JSON parsing
    try {
      const parsed = JSON.parse(result);
      if (typeof parsed === 'object' && parsed !== null) {
        obj = parsed;
      }
    } catch {
      // Not JSON, extract common ID patterns from text
      // Patterns for extracting fields from text (built-in + extensible via _patterns in flow-defaults.json)
      const builtinPatterns: Array<{ field: string; regex: RegExp }> = [
        { field: 'storyId', regex: /Story\s+(B-[a-f0-9]+)/i },
        { field: 'bugId', regex: /Bug\s+(BUG-\d+)/ },
        { field: 'itemId', regex: /(CHK-\d+)/ },
        { field: 'phase', regex: /advanced to\s+(\w+)/ },
        { field: 'phase', regex: /\((\w+)\)\s*(?:with|$)/ },
      ];
      const extraPatterns = loadConfig().flows.patterns as Array<{ field: string; regex: string }> | undefined;
      const patterns = [
        ...builtinPatterns,
        ...(extraPatterns || []).map(p => ({ field: p.field, regex: new RegExp(p.regex) })),
      ];
      for (const { field, regex } of patterns) {
        const m = result.match(regex);
        if (m) obj[field] = m[1];
      }
    }
  } else if (typeof result === 'object') {
    obj = result as Record<string, unknown>;
  }

  // Only extract fields declared in outputFields (if declared)
  // If outputFields is empty, extract all
  if (outputFields.length > 0) {
    for (const field of outputFields) {
      if (field in obj) {
        context[field] = obj[field];
      }
    }
    for (const field of ['storyId', 'bugId', 'itemId', 'phase']) {
      if (field in obj && !(field in context)) {
        context[field] = obj[field];
      }
    }
  } else {
    Object.assign(context, obj);
  }
}

/**
 * Build input arguments from context based on @input field names.
 * If a field is missing from context, use default mock value.
 */
function buildInputFromContext(
  inputFields: string[],
  context: Record<string, unknown>,
  flowName?: string,
): unknown {
  if (inputFields.length === 0) return undefined;

  const defaults = autoDefaults(inputFields, context, flowName);

  const input: Record<string, unknown> = {};
  for (const field of inputFields) {
    // phase special handling: always use derived next step, not current value from context
    if (field === 'phase') {
      input[field] = defaults[field];
    } else if (field in context) {
      input[field] = context[field];
    } else if (field in defaults) {
      input[field] = defaults[field];
    }
  }

  return input;
}

// ── Sandbox Preparation ──

/**
 * Ensure sandbox environment meets preconditions for function execution.
 * Auto-determine based on data in context, not hardcoded by function name.
 */
function ensureSandboxReady(
  sandboxDir: string,
  handlers: any,
  context: Record<string, unknown>,
): void {
  const storyId = context.storyId as string | undefined;
  if (!storyId) return;

  // Extract first itemId from checklist into context (if not already present)
  if (!context.itemId) {
    try {
      const cl = handlers.checklist_get({ storyId });
      if (cl.items.length > 0) {
        context.itemId = cl.items[0].id;
      }
    } catch { /* ignore */ }
  }

  // Ensure stub code files exist (so task_coverage passes)
  const fakeSrcDir = join(sandboxDir, 'packages', 'main', 'src');
  if (!existsSync(join(fakeSrcDir, 'e2e-stub.ts'))) {
    mkdirSync(fakeSrcDir, { recursive: true });
    writeFileSync(
      join(fakeSrcDir, 'e2e-stub.ts'),
      [
        'export function e2eStub() {}',
        '',
      ].join('\n'),
      'utf-8',
    );
  }

  // Ensure checklist items have complete testIntent (required by PLAN→DEV gate)
  try {
    const cl = handlers.checklist_get({ storyId });
    const defaultIntent = {
      happy: [{ desc: 'E2E happy path', type: 'cli_blackbox' }],
      edge: [{ desc: 'E2E edge case', type: 'cli_blackbox' }],
      adversarial: [{ desc: 'E2E adversarial case', type: 'cli_blackbox' }],
    };
    for (const item of cl.items) {
      if (!item.testIntent) {
        handlers.checklist_update({ storyId, itemId: item.id, testIntent: defaultIntent });
      }
    }
  } catch {
    // ignore
  }

  // Ensure the INIT→INIT_CHECK reviewer signature artifact exists.
  try {
    const detail = handlers.story_get({ storyId, detail: true });
    const phase = detail?.index?.phase || context.phase;
    if (phase === 'INIT') {
      handlers.scope_boundary_set({
        storyId,
        mode: 'feature',
        allowedScope: [
          'Run the story lifecycle e2e through the minimal generated checklist.',
          'Exercise lifecycle gate evidence required before INIT_CHECK.',
        ],
        excludedScope: [
          'Do not expand the generated e2e story beyond lifecycle validation.',
        ],
        userConfirmed: true,
        confirmation: 'E2E sandbox uses a fixed user-confirmed boundary for the generated lifecycle story.',
        actor: 'flow-e2e',
      });
      handlers.execution_boundary_set({
        storyId,
        allowedCommands: [
          'story_create',
          'scope_boundary_set',
          'execution_boundary_set',
          'scope_freeze_check',
          'init_check_set',
          'story_advance',
          'checklist_update',
          'task_coverage',
          'test_auto',
        ],
        allowedTools: ['lattice-flow-e2e'],
        allowedPaths: [
          'docs/story/actives',
          'packages/main/src',
          'packages/main/tests',
        ],
        excludedPaths: ['docs/story/drafts'],
        notes: 'Flow e2e sandbox may only touch generated story metadata and source/test paths needed for lifecycle validation.',
        actor: 'flow-e2e',
      });
      handlers.scope_freeze_check({
        storyId,
        status: 'PASS',
        note: 'E2E sandbox scope and execution boundaries are fixed before INIT_CHECK.',
        actor: 'flow-e2e',
      });
      handlers.init_check_set({ storyId, issues: [], agentId: 'lattice-review-story-init' });
      handlers.init_check_set({ storyId, issues: [], agentId: 'product-reviewer' });
    }
  } catch {
    // ignore
  }

  // Ensure story_review passes (PLAN→DEV gate requires blockerCount=0)
  try {
    handlers.story_review({ storyId });
  } catch {
    // ignore — review may have already passed or the story is not in PLAN phase
  }

  // Ensure all checklist items are done
  try {
    const cl = handlers.checklist_get({ storyId });
    for (const item of cl.items) {
      if (item.status !== 'done') {
        handlers.checklist_update({ storyId, itemId: item.id, status: 'done' });
      }
    }
  } catch {
    // ignore
  }
}

// ── Failure Diagnosis ──

/**
 * Generate a fix hint based on the error message.
 */
function diagnoseFailure(
  errorMsg: string,
  functionName: string,
  inputFields: string[],
  input: unknown,
  context: Record<string, unknown>,
): string {
  const inputObj = input as Record<string, unknown> | undefined;

  // Missing/undefined fields
  if (/undefined|not found|missing/i.test(errorMsg)) {
    const undefinedFields = inputFields.filter(f =>
      inputObj && (inputObj[f] === undefined || inputObj[f] === null)
    );
    if (undefinedFields.length > 0) {
      return `Input fields [${undefinedFields.join(', ')}] are empty. ` +
        `Please configure default values for these fields in flow-defaults.json, ` +
        `or check whether the previous step's @output contains these fields.`;
    }
  }

  // State transition failed
  if (/cannot transition|invalid.*phase/i.test(errorMsg)) {
    return `State transition failed. Current context.phase=${context.phase || 'unknown'}. ` +
      `Check whether the @flow step order is correct, or whether the preceding steps completed successfully.`;
  }

  // File does not exist
  if (/file not found|ENOENT/i.test(errorMsg)) {
    return `Dependency file does not exist. If this is a sandbox environment issue, check whether ensureSandboxReady covers this scenario. ` +
      `If this is a code path issue, check whether the path fields in @input are correct.`;
  }

  // Generic hint
  return `Function ${functionName} threw an error. ` +
    `Arguments passed in: ${JSON.stringify(input)}. ` +
    `Current context: ${JSON.stringify(Object.keys(context))}。` +
    `Please check whether the function logic or @input/@output annotations match.`;
}

// ── Flow E2E Runner ──

export async function runFlowE2E(flowName: string, scanRoot: string): Promise<FlowE2EResult> {
  const tasks = scan(scanRoot);
  const flows = extractFlows(tasks);
  const targetFlow = flows.find(f => f.name === flowName);

  if (!targetFlow) {
    return {
      flow: flowName,
      steps: [{ step: 'flow-lookup', passed: false, error: `Flow "${flowName}" not found` }],
      allPassed: false,
    };
  }

  // projectRoot is intentionally isolated: flow e2e must not write story
  // artifacts or worktree metadata into the developer's real checkout.
  const projectRoot = process.env.LATTICE_E2E_PROJECT_ROOT;
  const sandbox = await createSandbox(projectRoot);
  const steps: FlowE2EStepResult[] = [];
  const context: Record<string, unknown> = {};

  try {
    const { handlers, dir } = sandbox;

    for (const flowStep of targetFlow.steps) {
      const fn = (handlers as any)[flowStep.functionName];

      if (typeof fn !== 'function') {
        steps.push({
          step: `${flowStep.functionName} (step ${flowStep.step})`,
          passed: false,
          error: `Function "${flowStep.functionName}" not found in handlers`,
        });
        continue;
      }

      const stepName = `${flowStep.functionName} (step ${flowStep.step})`;
      const inputFields = parseFieldNames(flowStep.input);
      let input: unknown;

      try {
        ensureSandboxReady(dir, handlers, context);
        input = buildInputFromContext(inputFields, context, flowName);
        if (flowStep.functionName === 'story_create' && input && typeof input === 'object') {
          (input as Record<string, unknown>).background = defaultBackground();
        }
        if (flowStep.functionName === 'test_auto' && input && typeof input === 'object') {
          (input as Record<string, unknown>).dryRun = true;
        }
        const result = await Promise.resolve(fn.call(handlers, input));

        const outputFields = parseFieldNames(flowStep.output);
        extractOutputToContext(result, outputFields, context);

        steps.push({ step: stepName, passed: true, input, output: result });
      } catch (err: any) {
        // Generate fix hint
        const hint = diagnoseFailure(err.message, flowStep.functionName, inputFields, input, context);
        steps.push({ step: stepName, passed: false, error: err.message, input, hint });
      }
    }
  } finally {
    sandbox.cleanup();
  }

  return {
    flow: flowName,
    steps,
    allPassed: steps.every(s => s.passed),
  };
}
