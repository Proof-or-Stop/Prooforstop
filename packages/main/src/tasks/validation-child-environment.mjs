const VALIDATION_CHILD_ENVIRONMENT_KEY_SET = new Set(VALIDATION_CHILD_ENVIRONMENT_KEYS);
const HOST_ROUTING_ENVIRONMENT_KEYS = new Set([
  'HOME', 'USERPROFILE', 'XDG_CONFIG_HOME',
  // These finite keys are declared because nested CLI/shell code reads them,
  // but ambient values are authority, path-routing, or launcher bookkeeping.
  // Only the causal experiment pair and canonical PWD cross this boundary.
  'PROOF_OR_STOP_HEALTH_PATH',
  'PROOF_OR_STOP_REVIEWER_READONLY',
  'QUORUM_CLI_PROBE_COUNTER',
  'SHLVL',
  '_',
]);
const isHostRoutingKey = (key) => key.startsWith('GIT_') || HOST_ROUTING_ENVIRONMENT_KEYS.has(key);

export function validationChildEnvironment(
  overrides = {},
  source = process.env,
) {
  const environment = {};
  for (const key of VALIDATION_CHILD_ENVIRONMENT_KEYS) {
    if (isHostRoutingKey(key)) continue;
    const value = source[key];
    if (typeof value === 'string') environment[key] = value;
  }
  for (const [key, value] of Object.entries(overrides)) {
    if (!VALIDATION_CHILD_ENVIRONMENT_KEY_SET.has(key) || isHostRoutingKey(key)) {
      throw new Error(`validation child environment refuses undeclared or host-routing key ${key}`);
    }
    if (typeof value === 'string') environment[key] = value;
    else delete environment[key];
  }
  return environment;
}
