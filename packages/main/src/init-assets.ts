export function renderProofOrStopBootstrapScript(packageRootAbs: string): string {
  return `#!/usr/bin/env node
const { existsSync } = require('node:fs');
const { dirname, join } = require('node:path');
const { pathToFileURL } = require('node:url');
const { spawnSync } = require('node:child_process');

async function main() {
  const binDir = __dirname;
  const projectRoot = dirname(binDir);
  const coreCliEngineCandidates = [
    join(projectRoot, 'packages', 'main', 'dist', 'cli-engine.js'),
    join(projectRoot, 'node_modules', '@proof-or-stop', 'core', 'dist', 'cli-engine.js'),
    join(${jsString(packageRootAbs)}, 'dist', 'cli-engine.js'),
  ];

  for (const candidate of coreCliEngineCandidates) {
    if (!existsSync(candidate)) continue;
    const mod = await import(pathToFileURL(candidate).href);
    if (typeof mod.runCli !== 'function') {
      console.error(\`proof-or-stop local bootstrap candidate has no runCli export: \${candidate}\`);
      process.exit(1);
    }
    await mod.runCli();
    // Preserve a structured CLI failure. Unconditionally exiting 0 here hid
    // verify_codex/validate failures from every generated project bootstrap.
    process.exit(process.exitCode ?? 0);
  }

  // Selection is by CAPABILITY, not merely by exit status: a core-only install exits 0
  // from \`help\` but lacks aux_doc_list/verify_codex.
  const globalBinNames = ['proof-or-stop'];
  const isCapable = (out) => out.includes('aux_doc_list') && out.includes('verify_codex');
  let globalBin = globalBinNames[0];
  let probeOk = false;
  let firstProbe = null;
  for (const candidate of globalBinNames) {
    const attempt = spawnSync(candidate, ['help'], {
      encoding: 'utf8',
      stdio: ['pipe', 'pipe', 'pipe'],
      env: process.env,
    });
    const out = String(attempt.stdout || '') + String(attempt.stderr || '');
    if (firstProbe === null) firstProbe = { bin: candidate, out };
    if (attempt.status === 0 && isCapable(out)) {
      globalBin = candidate;
      probeOk = true;
      break;
    }
  }
  if (!probeOk && firstProbe) {
    globalBin = firstProbe.bin;
  }
  if (!probeOk) {
    console.error('bin/proof-or-stop.js could not find a local @proof-or-stop/core CLI engine or a capable global proof-or-stop.');
    console.error('');
    console.error('Checked local candidates:');
    for (const candidate of coreCliEngineCandidates) console.error(\`  - \${candidate}\`);
    console.error('');
    console.error('Recovery:');
    console.error('  - Install or update @proof-or-stop/core, then rerun: proof-or-stop init --verify-codex');
    console.error('  - In the Proof-or-Stop repository, run: npm run build');
    process.exit(1);
  }

  const result = spawnSync(globalBin, process.argv.slice(2), {
    stdio: 'inherit',
    env: process.env,
  });
  process.exit(result.status ?? 1);
}

module.exports = { main };

if (require.main === module) {
  main().catch(error => {
    console.error(error?.stack || String(error));
    process.exit(1);
  });
}
`;
}

