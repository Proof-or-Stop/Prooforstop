import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { StoryStore } from '../dist/core/store.js';
import { resetConfigCache } from '../dist/core/config.js';
import { acquireOwnerLease } from '../dist/core/story-owner-lease.js';
import { createChecklistHandlers } from '../dist/handlers/checklist.js';
import { createEvidencePlanHandlers } from '../dist/handlers/evidence-plan.js';
import { buildVerificationReuseCapsuleInvocation } from '../dist/core/verification-reuse-capsule.js';
import { runSingleAllowlistedCommand } from '../dist/core/validation-executor.js';

const started = performance.now();
const root = mkdtempSync(join(tmpdir(), 'intent-fingerprint-reuse-'));
const storyId = 'B-intent-fingerprint';
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
const write = (path, text) => { mkdirSync(join(root, path, '..'), { recursive: true }); writeFileSync(join(root, path), text); };
const commit = label => { git('add', '.'); git('commit', '-m', label); };
let executions = 0;
try {
  write('proof-or-stop.config.json', JSON.stringify({ scanRoot: 'packages/main', rootDir: 'src', storyDir: '.proof-or-stop/story/actives' }));
  write('packages/main/package.json', JSON.stringify({ name: '@proof-or-stop/core', version: '0.0.0-test' }));
  write('packages/main/src/base.txt', 'base');
  git('init', '-b', 'work'); git('config', 'user.name', 'Lab Test'); git('config', 'user.email', 'lab@example.test'); commit('base'); git('branch', 'main');
  resetConfigCache();
  const store = new StoryStore(root);
  store.writeStory(storyId, { storyId, name: 'intent-fingerprint', title: 'Dynamic intent fingerprints', description: 'Test dynamic intent reporting and exact reusable input changes.', type: 'chore', phase: 'DEV', priority: 'medium', createdAt: '2026-09-20T00:00:00.000Z', startedAt: null, endedAt: null });
  acquireOwnerLease(store.storyDirPath(storyId), { command: 'smoke_fixture_setup', cwd: root });
  const intent = (id, desc) => ({ id, desc, type: 'cli', priority: 'must' });
  store.writeChecklist(storyId, { items: [{ id: 'CHK-001', title: 'Actual user requirements', context: 'Bounded repair', status: 'in_progress', startTime: null, endTime: null, verificationIntent: { happy: [intent('INT-A', 'Show the accepted first result'), intent('INT-A-SECOND', 'Show the second acceptance from the same command'), intent('INT-B', 'Keep the independent result'), intent('INT-ORDINARY', 'Execute the ordinary program'), intent('INT-MISSING', 'Do not hide unverified requirements')], edge: [], adversarial: [] } }] });
  const ctx = { root, store, scanRoot: join(root, 'packages/main'), verificationCommandRunner: async (command, cwd, timeoutMs) => {
    executions++;
    return runSingleAllowlistedCommand(command, root, { cwd, timeoutMs });
  } };
  const handlers = createChecklistHandlers(ctx);
  const planner = createEvidencePlanHandlers(ctx);
  const report = () => planner.evidence_plan({ storyId, json: true });
  const pin = (intentRef, command, selector, file) => handlers.verification_evidence_add({ storyId, itemId: 'CHK-001', intentRef, kind: 'integration_test', command, selector, ...(file ? { file } : {}), result: 'pass', note: 'Real tool-executed fixture result.' });
  const shared = 'packages/main/src/shared.txt';
  write(shared, 'SHARED\n');
  const commandFor = (name, contents) => {
    const input = `packages/main/src/${name}.txt`, manifest = `packages/main/${name}.verification-dependencies.json`;
    write(input, contents);
    write(manifest, JSON.stringify({ schemaVersion: 'proof-or-stop.verifier-dependency-manifest.v2', capsuleProfile: 'proof-or-stop.verification-reuse-capsule.v1', files: [input, shared] }));
    return { input, manifest, command: buildVerificationReuseCapsuleInvocation({ cwd: root, manifestPath: manifest, files: [input, shared] }).command };
  };
  const a = commandFor('a', 'A_OK A_SECOND\n'), b = commandFor('b', 'B_OK\n');
  commit('declared independent inputs');
  await pin('INT-A', a.command, 'A_OK', a.manifest);
  await pin('INT-A-SECOND', a.command, 'A_SECOND', a.manifest);
  await pin('INT-B', b.command, 'B_OK', b.manifest);
  await pin('INT-ORDINARY', 'node -e "console.log(\'ORDINARY_OK\')"', 'ORDINARY_OK');
  const initial = report();
  write('unrelated.txt', 'unrelated change'); commit('unrelated change');
  const beforeChecklist = readFileSync(store.storyFilePath(storyId, 'checklist.json'), 'utf8');
  const beforeGit = git('status', '--porcelain');
  const unrelated = report();
  assert.ok(unrelated.buckets.rerun.some(row => row.intentRef === 'INT-ORDINARY'), 'ordinary stale evidence must not be advertised as refresh-only');
  assert.ok(initial.fingerprints, 'plan exposes dynamic intent fingerprints');
  const graph = r => r.fingerprints;
  const row = (r, id) => graph(r).intents.find(x => x.intentRef === id);
  assert.equal(graph(initial).intents.length, 5, 'include actual pending requirements, not only receipt rows');
  assert.equal(row(initial, 'INT-A').description, 'Show the accepted first result');
  assert.equal(row(initial, 'INT-MISSING').action, 'missing');
  assert.equal(row(initial, 'INT-A').executionKey, row(initial, 'INT-A-SECOND').executionKey, 'selectors do not split execution identity');
  assert.equal(row(initial, 'INT-A').currentFingerprint, row(unrelated, 'INT-A').currentFingerprint, 'unrelated material does not change a proven complete input fingerprint');
  assert.notEqual(row(initial, 'INT-ORDINARY').currentFingerprint, row(unrelated, 'INT-ORDINARY').currentFingerprint, 'incomplete input closure keeps strict material binding');
  assert.equal(row(unrelated, 'INT-A').action, 'reuse');
  assert.equal(readFileSync(store.storyFilePath(storyId, 'checklist.json'), 'utf8'), beforeChecklist, 'plan never rewrites evidence');
  assert.equal(git('status', '--porcelain'), beforeGit, 'plan never changes the checkout');
  executions = 0;
  await handlers.verification_evidence_refresh_stale({ storyId });
  assert.equal(executions, 1, 'unrelated drift reruns only the ordinary command');
  const refreshed = report();
  assert.equal(row(refreshed, 'INT-A').currentFingerprint, row(unrelated, 'INT-A').currentFingerprint, 'publication timestamps and hashes do not perturb input fingerprints');
  const originalExecution = store.readChecklist(storyId).items[0].verificationEvidence.find(e => e.intentRef === 'INT-B').receipt.executionReceipt.executionReceiptDigest;
  write(a.input, 'A_OK A_SECOND changed\n'); commit('change one shared input');
  const changed = report();
  assert.notEqual(graph(refreshed).rootFingerprint, graph(changed).rootFingerprint);
  assert.notEqual(row(refreshed, 'INT-A').currentFingerprint, row(changed, 'INT-A').currentFingerprint);
  assert.notEqual(row(refreshed, 'INT-A-SECOND').currentFingerprint, row(changed, 'INT-A-SECOND').currentFingerprint);
  assert.equal(row(refreshed, 'INT-B').currentFingerprint, row(changed, 'INT-B').currentFingerprint);
  assert.equal(row(changed, 'INT-A').action, 'rerun');
  executions = 0;
  await handlers.verification_evidence_refresh_stale({ storyId });
  assert.equal(executions, 2, 'one changed reusable group plus ordinary fallback, not one launch per intent');
  assert.equal(store.readChecklist(storyId).items[0].verificationEvidence.find(e => e.intentRef === 'INT-B').receipt.executionReceipt.executionReceiptDigest, originalExecution, 'unaffected execution stays immutable');
  write(shared, 'SHARED changed\n'); commit('change shared dependency');
  const sharedChange = report();
  assert.equal(row(sharedChange, 'INT-A').action, 'rerun');
  assert.equal(row(sharedChange, 'INT-B').action, 'rerun');
  executions = 0;
  await handlers.verification_evidence_refresh_stale({ storyId });
  assert.equal(executions, 3, 'shared dependency reruns both reusable groups and strict ordinary fallback');
  const manifestBytes = readFileSync(join(root, b.manifest));
  rmSync(join(root, b.manifest));
  assert.equal(row(report(), 'INT-B').action, 'rerun', 'missing input closure never reuses a matching prior result');
  write(b.manifest, manifestBytes);
  const failedProjection = store.readChecklist(storyId);
  failedProjection.items[0].verificationEvidence.find(e => e.intentRef === 'INT-B').result = 'fail';
  store.writeChecklist(storyId, failedProjection);
  assert.equal(row(report(), 'INT-B').action, 'rerun', 'a matching receipt never overrides a recorded failure');
  failedProjection.items[0].verificationEvidence.find(e => e.intentRef === 'INT-B').result = 'pass';
  store.writeChecklist(storyId, failedProjection);
  const current = report();
  const cl = store.readChecklist(storyId);
  cl.items[0].verificationIntent.happy.push(intent('INT-ADDED', 'A newly requested user outcome'));
  store.writeChecklist(storyId, cl);
  const added = report();
  assert.equal(graph(added).intents.length, 6, 'derive changing intent count dynamically');
  assert.notEqual(graph(current).rootFingerprint, graph(added).rootFingerprint, 'added unverified intent changes the root');
  const saved = store.readChecklist(storyId);
  saved.items[0].verificationIntent.happy.reverse(); store.writeChecklist(storyId, saved);
  assert.equal(graph(report()).rootFingerprint, graph(added).rootFingerprint, 'explicit stable IDs make ordering irrelevant');
  saved.items[0].verificationIntent.happy.find(i => i.id === 'INT-A').desc = 'Changed acceptance requirement'; store.writeChecklist(storyId, saved);
  assert.notEqual(row(report(), 'INT-A').currentFingerprint, row(added, 'INT-A').currentFingerprint, 'acceptance meaning participates in its own fingerprint');
  const tampered = store.readChecklist(storyId);
  tampered.items[0].verificationEvidence.find(e => e.intentRef === 'INT-B').receipt.executionReceipt.authenticity.signature = 'forged';
  store.writeChecklist(storyId, tampered);
  assert.equal(row(report(), 'INT-B').action, 'invalid', 'unchanged input hash never overrides invalid signatures');
  const text = planner.evidence_plan({ storyId });
  const duplicate = store.readChecklist(storyId);
  duplicate.items[0].verificationIntent.happy.push(intent('INT-A', 'Conflicting duplicate requirement'));
  store.writeChecklist(storyId, duplicate);
  assert.throws(report, /Duplicate verification intent identity/, 'duplicate identity never hides an intent');
  assert.match(text, /A newly requested user outcome/, 'text report shows user intent wording');
  assert.match(text, /missing_dependency_manifest/, 'ordinary closure limitation is explained');
  console.log('INTENT_FINGERPRINT_REUSE PASS ' + JSON.stringify({ dynamicIntentCount: 6, unrelatedExecutions: 1, affectedExecutions: 2, sharedDependencyExecutions: 3, ordinaryFallbackExecutionsPerDrift: 1, changedReusableGroupExecutions: 1, unchangedReusableGroupExecutions: 0, wallSeconds: (performance.now() - started) / 1000 }));
} finally { rmSync(root, { recursive: true, force: true }); }
