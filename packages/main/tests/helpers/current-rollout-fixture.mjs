// Current producer receipts only; never imports historical Story artifacts.
// This fixture changes process.cwd and environment; do not use with concurrency:true.
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname, join, resolve} from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
export async function withCurrentRolloutFixture(callback, options = {}) {
  const repositoryRoot = options.repositoryRoot ?? resolve(dirname(fileURLToPath(import.meta.url)), '../../../..');
  const load = path => import(pathToFileURL(join(repositoryRoot,'packages/main/dist',path)).href);
  const [{StoryStore},{resetConfigCache},rollout,{createProofStoryHandlers},{STATE_DIR_NAMES},{sanitizedFixtureChildEnvironment}] = await Promise.all([
    load('core/store.js'),load('core/config.js'),load('core/acceptance-rollout.js'),load('handlers/proofstory.js'),load('core/brand-paths.js'),load('tasks/fixture-environment.js')]);
  const previousCwd=process.cwd();
  const previousEnv={...process.env};
  const clean=sanitizedFixtureChildEnvironment(process.env);
  for(const key of Object.keys(process.env)) if(!(key in clean)) delete process.env[key];
  Object.assign(process.env,clean);
  let root;
  const git=(cwd,args)=>execFileSync('git',args,{cwd,encoding:'utf8',stdio:['ignore','pipe','pipe']}).trim();
  const write=(path,text)=>{mkdirSync(dirname(path),{recursive:true});writeFileSync(path,text);};
  try {
    process.chdir(repositoryRoot);
    // A supplied input must be generated by the current production runner. Current
    // runner digest and cryptographic source receipts are checked below, not re-signed.
    const cohort=options.cohortPath
      ? JSON.parse(readFileSync(options.cohortPath,'utf8'))
      : await (await import(pathToFileURL(join(repositoryRoot,'scripts/run-proofstory-acceptance-rollout-cohort.mjs')).href)).runProofStoryAcceptanceRolloutCohort();
    root=mkdtempSync(join(tmpdir(),'u03-current-rollout-'));
    git(root,['init','-b','main']);git(root,['config','user.email','rollout-fixture@example.test']);git(root,['config','user.name','Rollout Fixture']);
    // Explicit fixture trust provisioning for the freshly issued source receipts.
    // This copies verifier trust, never copies or re-signs a historical report.
    const key='proof-or-stop-acceptance-rollout-verifier-v1.key';
    copyFileSync(join(resolve(repositoryRoot,git(repositoryRoot,['rev-parse','--git-common-dir'])),key),join(root,'.git',key));
    write(join(root,'proof-or-stop.config.json'),JSON.stringify({storyDir:'.proof-or-stop/story/actives',requirementsDir:'docs/requirements',scanRoot:'packages/main',rootDir:'src',outDir:'packages/main/dist',testsDir:'packages/main/tests',fixturesDir:'packages/main/tests/fixtures',proofStory:{acceptanceRolloutGateMode:'enforce'}}));
    write(join(root,'scripts/run-proofstory-acceptance-rollout-cohort.mjs'),readFileSync(join(repositoryRoot,'scripts/run-proofstory-acceptance-rollout-cohort.mjs')));
    mkdirSync(join(root,'packages/main'),{recursive:true});
    symlinkSync(join(repositoryRoot,'packages/main/dist'),join(root,'packages/main/dist'),'dir');symlinkSync(join(repositoryRoot,'bin'),join(root,'bin'),'dir');
    write(join(root,'packages/main/src/control.ts'),'export const control=true;\n');
    write(join(root,'.gitignore'),STATE_DIR_NAMES.map(dir=>`${dir}/activity.jsonl`).join('\n')+'\n');
    const store=new StoryStore(root),storyId='B-current-rollout-fixture',at=new Date().toISOString();
    // Fixture data only. All signed rollout observations came from the real producer.
    store.writeStory(storyId,{storyId,name:'current-rollout-fixture',title:'Current rollout fixture',description:'Isolated current rollout consumer',type:'feature',phase:'DEV',priority:'high',createdAt:at,startedAt:at,endedAt:null,events:[]});
    git(root,['add','.']);git(root,['commit','-m','seed current rollout consumer']);git(root,['switch','-c',`story/${storyId}`]);
    write(join(root,'packages/main/src/control.ts'),'export const control=true; export const revision=1;\n');git(root,['add','.']);git(root,['commit','-m','add story owned control']);
    process.chdir(root);resetConfigCache();
    const report=rollout.deriveAcceptanceRolloutReport({storyId,cohort,binding:rollout.currentAcceptanceRolloutBinding(root,root),gitCwd:root});
    assert.equal(report.verdict,'pass',JSON.stringify(report.diagnostics));
    const artifact=rollout.issueAcceptanceRolloutArtifact({gitCwd:root,report,issuedAt:at});
    store.writeAcceptanceRolloutReport(storyId,artifact);
    const handlers=createProofStoryHandlers({root,scanRoot:join(root,'packages/main'),store});
    const read=command=>JSON.parse(handlers[command]({storyId,json:true}));
    const ready=read('acceptance_rollout_report_read');assert.equal(ready.ok,true,JSON.stringify(ready));assert.equal(ready.receipt,'current');assert.equal(ready.quorum,'full-3x2');
    return await callback({root,storyId,store,cohort,artifact,read,rollout});
  } finally {
    process.chdir(previousCwd);resetConfigCache();
    if(root)rmSync(root,{recursive:true,force:true});
    for(const key of Object.keys(process.env))if(!(key in previousEnv))delete process.env[key];
    Object.assign(process.env,previousEnv);
  }
}
